package main

import (
	"encoding/json"
	"fmt"
	"net/http"
	"strings"
	"sync"
	"time"
)

type ollamaTag struct {
	Name    string `json:"name"`
	Model   string `json:"model"`
	Size    int64  `json:"size"`
	Details struct {
		Family string `json:"family"`
	} `json:"details"`
}

var (
	ollamaEnabledMu sync.Mutex
	ollamaEnabled   = true
)

func setOllamaEnabled(enabled bool) {
	ollamaEnabledMu.Lock()
	defer ollamaEnabledMu.Unlock()
	ollamaEnabled = enabled
}

func getOllamaEnabled() bool {
	ollamaEnabledMu.Lock()
	defer ollamaEnabledMu.Unlock()
	return ollamaEnabled
}

func ollamaListModels(client *http.Client, baseURL string) ([]ollamaTag, error) {
	bounded := *client
	bounded.Timeout = 3 * time.Second
	resp, err := bounded.Get(strings.TrimRight(baseURL, "/") + "/api/tags")
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode < http.StatusOK || resp.StatusCode >= http.StatusMultipleChoices {
		return nil, fmt.Errorf("ollama /api/tags returned %s", resp.Status)
	}
	var payload struct {
		Models []ollamaTag `json:"models"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&payload); err != nil {
		return nil, fmt.Errorf("decode ollama tags: %w", err)
	}
	return payload.Models, nil
}

func ollamaModels(client *http.Client, cfg Config) []CuratedModel {
	models := []CuratedModel{}
	if !getOllamaEnabled() {
		return models
	}
	tags, err := ollamaListModels(client, cfg.OllamaURL)
	if err != nil {
		return models
	}
	for _, tag := range tags {
		family := tag.Details.Family
		if family == "" {
			family = "unknown"
		}
		models = append(models, CuratedModel{
			ID:              tag.Name,
			Name:            tag.Name,
			Source:          "ollama",
			Pipeline:        "direct-svg",
			Framework:       "Ollama / " + family,
			Description:     "SVG text generated by an external Ollama model, processed by the Rust SVG stage.",
			Tags:            []string{"ollama", family},
			CPUFriendly:     true,
			FitsGPU:         true,
			EstimatedVRAMMB: 0,
		})
	}
	return models
}

func ollamaStatuses(client *http.Client, cfg Config) map[string]any {
	statuses := map[string]any{}
	if !getOllamaEnabled() {
		return statuses
	}
	tags, err := ollamaListModels(client, cfg.OllamaURL)
	if err != nil {
		return statuses
	}
	for _, tag := range tags {
		sizeMB := float64(tag.Size) / (1024 * 1024)
		statuses[tag.Name] = map[string]any{
			"model_id":         tag.Name,
			"status":           "ready",
			"progress":         100,
			"downloaded_mb":    sizeMB,
			"total_mb":         sizeMB,
			"loaded_in_memory": false,
		}
	}
	return statuses
}

func ollamaReachable(client *http.Client, cfg Config) bool {
	if !getOllamaEnabled() {
		return false
	}
	_, err := ollamaListModels(client, cfg.OllamaURL)
	return err == nil
}
